export const PROVINCES = REGIONS.flatMap((g) =>
  g.provinces.map((p) => ({ ...p, region: g.region }))
);

const CITY_INDEX = new Map(PROVINCES.map((p) => [p.code, new Set(p.cities)]));

export function getProvince(code) {
  return PROVINCES.find((p) => p.code === String(code)) || null;
}

export function isValidCity(code, city) {
  const set = CITY_INDEX.get(String(code));
  return !!set && set.has(city);
}

